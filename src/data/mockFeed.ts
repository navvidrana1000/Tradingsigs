// Dynamically generate authentic market signals calibrated directly to live market prices for all tickers
export function generateLiveSignalsFromTickers(tickers: AssetTicker[]): SignalRecord[] {
  const allSetups: SignalRecord[] = [];

  tickers.forEach((ticker) => {
    const isLong = ticker.trend === "BULLISH" || (ticker.trend !== "BEARISH" && ticker.delta_z >= 0);
    const scalp = createInstitutionalSetup(ticker, "SCALP_5M_15M", { isLong });
    const swing = createInstitutionalSetup(ticker, "SWING_1H_4H", { isLong });
    allSetups.push(scalp, swing);
  });

  return allSetups.sort((a, b) => (b.confidence_score ?? 80) - (a.confidence_score ?? 80));
}

export function getAllMarketSignals(): SignalRecord[] {
  return generateLiveSignalsFromTickers(INITIAL_TICKERS);
}

